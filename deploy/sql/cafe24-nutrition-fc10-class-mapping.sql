-- sync fallback nutrition from matching food_code (prefer MFDS then FC10)
UPDATE public.cm_food_class c
   SET fb_kcal = n.kcal,
       fb_carb_g = n.carb_g,
       fb_protein_g = n.protein_g,
       fb_fat_g = n.fat_g,
       updated_at = now()
  FROM public.cm_food_nutrition n
 WHERE n.food_code = c.food_code
   AND n.is_enabled = true
   AND n.ctid = (
         SELECT n2.ctid FROM public.cm_food_nutrition n2
          WHERE n2.food_code = c.food_code AND n2.is_enabled = true
          ORDER BY CASE n2.nutrition_version WHEN 'MFDS-2025.12' THEN 2 WHEN 'FC10.4' THEN 1 ELSE 0 END DESC
          LIMIT 1
       );

